export async function seedSubmissionForJob(submissionId: string, leadData: any) {
  // Populate default 42 requirements for a newly created submission workspace
  const now = new Date().toISOString();
  
  // Determine conditionals based on job inputs
  const isGshp = (leadData.technology || '').toLowerCase().includes('ground');
  const isSelfBuild = (leadData.property_status || '').toLowerCase().includes('self-build');
  const isOffGasUplift = (leadData.grant_category || '').includes('£9,000') || ((leadData.on_off_gas_grid || '').toLowerCase().includes('off') && ['Heating Oil', 'Bulk LPG'].includes(leadData.existing_fuel || ''));
  const isCylinderApplicable = leadData.cylinder_applicable !== 0;

  for (const tpl of MASTER_REQUIREMENTS_TEMPLATE) {
    let initialStatus = 'Pending';
    let isCond = tpl.is_conditional || 0;

    // Apply conditional rules automatically
    if (tpl.condition_rule === 'GSHP_ONLY' && !isGshp) {
      initialStatus = 'Not Required';
    } else if (tpl.condition_rule === 'SELF_BUILD_ONLY' && !isSelfBuild) {
      initialStatus = 'Not Required';
    } else if (tpl.condition_rule === 'OFF_GAS_UPLIFT_ONLY' && !isOffGasUplift) {
      initialStatus = 'Not Required';
    } else if (tpl.condition_rule === 'CYLINDER_ONLY' && !isCylinderApplicable) {
      initialStatus = 'Not Required';
    }

    const itemId = `sub_item_${Math.random().toString(36).substring(2, 11)}_${Date.now()}`;
    await db.execute(
      `INSERT INTO submission_items (
        id, submission_id, stage_code, stage_name, section_name, requirement_key,
        title, short_description, what_is_this, why_required, who_completes, who_submits,
        customer_signature_type, classification, status, is_conditional, condition_rule,
        evidence_required, authority, source_url, clause_page, sort_order, created_at, updated_at
      ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
      [
        itemId, submissionId, tpl.stage_code, tpl.stage_name, tpl.section_name, tpl.requirement_key,
        tpl.title, tpl.short_description, tpl.what_is_this, tpl.why_required, tpl.who_completes, tpl.who_submits,
        tpl.customer_signature_type, tpl.classification, initialStatus, isCond, tpl.condition_rule || null,
        tpl.evidence_required, tpl.authority, tpl.source_url, tpl.clause_page, tpl.sort_order, now, now
      ]
    );
  }
}
