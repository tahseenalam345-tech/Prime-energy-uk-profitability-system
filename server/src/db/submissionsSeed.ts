import { db } from './connection.js';

export async function initSubmissionsTables() {
  // 1. Submissions Table
  await db.exec(`
    CREATE TABLE IF NOT EXISTS submissions (
      id TEXT PRIMARY KEY,
      job_reference TEXT NOT NULL UNIQUE,
      lead_id TEXT,
      customer_name TEXT NOT NULL,
      customer_email TEXT,
      customer_phone TEXT,
      property_address TEXT NOT NULL,
      postcode TEXT,
      country TEXT DEFAULT 'England',
      technology TEXT DEFAULT 'Air-to-water heat pump',
      property_status TEXT DEFAULT 'Existing property',
      on_off_gas_grid TEXT DEFAULT 'On gas grid',
      existing_fuel TEXT DEFAULT 'Mains Gas',
      cylinder_applicable INTEGER DEFAULT 1,
      installation_date DATE,
      commissioning_date DATE,
      bus_voucher_reference TEXT,
      bus_voucher_expiry DATE,
      mcs_certificate_number TEXT,
      grant_category TEXT DEFAULT '£7,500 Standard AWHP/GSHP',
      current_stage TEXT DEFAULT '01 Eligibility',
      overall_status TEXT DEFAULT 'Pending',
      completion_percentage REAL DEFAULT 0.0,
      next_action TEXT DEFAULT 'Complete pre-check eligibility',
      assigned_to TEXT,
      notes TEXT,
      six_year_retention_date DATE,
      created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
      updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
    );
  `);

  // 2. Submission Requirement Items Table
  await db.exec(`
    CREATE TABLE IF NOT EXISTS submission_items (
      id TEXT PRIMARY KEY,
      submission_id TEXT NOT NULL,
      stage_code TEXT NOT NULL,
      stage_name TEXT NOT NULL,
      section_name TEXT NOT NULL,
      requirement_key TEXT NOT NULL,
      title TEXT NOT NULL,
      short_description TEXT,
      what_is_this TEXT,
      why_required TEXT,
      who_completes TEXT,
      who_submits TEXT,
      customer_signature_type TEXT DEFAULT 'No signature',
      classification TEXT DEFAULT 'OFFICIAL',
      status TEXT DEFAULT 'Pending',
      is_conditional INTEGER DEFAULT 0,
      condition_rule TEXT,
      due_date DATE,
      completed_date DATE,
      responsible_person TEXT,
      reviewer_person TEXT,
      evidence_required TEXT,
      reference_number TEXT,
      notes TEXT,
      authority TEXT,
      source_url TEXT,
      document_version TEXT,
      clause_page TEXT,
      last_verified_date DATE,
      sort_order INTEGER DEFAULT 0,
      created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
      updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
      FOREIGN KEY (submission_id) REFERENCES submissions(id) ON DELETE CASCADE
    );
  `);

  // 3. Submission Evidence Files Table
  await db.exec(`
    CREATE TABLE IF NOT EXISTS submission_evidence (
      id TEXT PRIMARY KEY,
      submission_id TEXT NOT NULL,
      item_id TEXT NOT NULL,
      file_name TEXT NOT NULL,
      file_type TEXT,
      file_size INTEGER,
      file_path_or_url TEXT NOT NULL,
      reference_no TEXT,
      uploaded_by TEXT,
      notes TEXT,
      uploaded_at DATETIME DEFAULT CURRENT_TIMESTAMP,
      FOREIGN KEY (submission_id) REFERENCES submissions(id) ON DELETE CASCADE,
      FOREIGN KEY (item_id) REFERENCES submission_items(id) ON DELETE CASCADE
    );
  `);

  // 4. Submission Audit Logs Table
  await db.exec(`
    CREATE TABLE IF NOT EXISTS submission_audit_logs (
      id TEXT PRIMARY KEY,
      submission_id TEXT NOT NULL,
      item_id TEXT,
      user_id TEXT,
      user_name TEXT,
      field_changed TEXT NOT NULL,
      old_value TEXT,
      new_value TEXT,
      notes TEXT,
      changed_at DATETIME DEFAULT CURRENT_TIMESTAMP,
      FOREIGN KEY (submission_id) REFERENCES submissions(id) ON DELETE CASCADE
    );
  `);
}

